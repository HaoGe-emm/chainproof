import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { keccak256 } from "viem";
import { compile, root, saveArtifacts } from "./compile.mjs";
import { clients, assertLocal } from "./runtime.mjs";
import { refuseExistingDeployment } from "./setup-safety.mjs";
export async function setup() {
  await refuseExistingDeployment(path.join(root,".local-evm"));
  const { publicClient: client, wallet } = clients(); await assertLocal(client);
  if(await client.getBlockNumber({cacheTime:0})!==BigInt(0)) throw new Error("Refusing deployment into a nonempty local chain. No state was changed.");
  const artifact = await compile(); const dir = await saveArtifacts(artifact);
  // ABI is generated from compiler output, not invented separately.
  const old = artifact.contracts["ChainProof.sol"].ChainProof;
  const v2 = artifact.contracts["ChainProofVersionRegistry.sol"].ChainProofVersionRegistry;
  await writeFile(path.join(root, "lib/version-registry-abi.ts"), `// Generated by compile:chain:local / setup:chain:local from Solidity 0.8.20.\nexport const versionRegistryAbi = ${JSON.stringify(v2.abi, null, 2)} as const;\n`);
  const accounts = await client.request({ method: "eth_accounts" });
  const deploy = async (contract, args = []) => {
    await assertLocal(client);
    const tx = await wallet(accounts[0]).deployContract({ abi: contract.abi, bytecode: `0x${contract.evm.bytecode.object}`, args });
    const receipt = await client.waitForTransactionReceipt({ hash: tx });
    if (receipt.status !== "success" || !receipt.contractAddress) throw new Error("Local deployment failed.");
    return receipt;
  };
  const original = (await deploy(old)).contractAddress;
  const deployed = await deploy(v2, [original]); const registry = deployed.contractAddress;
  const samples = [];
  await mkdir(path.join(dir, "files"), { recursive: true });
  for (let i = 1; i <= 5; i++) {
    const content = `ChainProof actual local EVM file version ${i}\n`;
    const hash = `0x${createHash("sha256").update(content).digest("hex")}`;
    const owner = i === 4 ? accounts[1] : accounts[0];
    const tx = await wallet(owner).writeContract({ address: original, abi: old.abi, functionName: "registerProof", args: [hash] });
    if ((await client.waitForTransactionReceipt({ hash: tx })).status !== "success") throw new Error("Local registration failed.");
    const name = `local-version-${i}.txt`; await writeFile(path.join(dir, "files", name), content);
    samples.push({ hash, owner, name });
  }
  const gas = {};
  for (const [name, functionName, args] of [
    ["createWork", "createWork", [samples[0].hash]],
    ["addVersion2", "addVersion", [BigInt(1), samples[1].hash, BigInt(1)]],
    ["addVersion3", "addVersion", [BigInt(1), samples[2].hash, BigInt(2)]],
  ]) {
    const tx = await wallet(accounts[0]).writeContract({ address: registry, abi: v2.abi, functionName, args });
    const receipt = await client.waitForTransactionReceipt({ hash: tx });
    if (receipt.status !== "success") throw new Error("Local seed transaction failed.");
    gas[name] = receipt.gasUsed.toString();
  }
  for (const [name, functionName, args] of [["getWork", "getWork", [BigInt(1)]], ["getVersion", "getVersion", [BigInt(1), BigInt(1)]]]) {
    gas[`${name}Estimate`] = (await client.estimateContractGas({ account: accounts[0], address: registry, abi: v2.abi, functionName, args })).toString();
  }
  const [genesis, deploymentBlock, originalCode, registryCode] = await Promise.all([client.getBlock({ blockNumber: BigInt(0) }), client.getBlock({ blockNumber: deployed.blockNumber }), client.getCode({ address: original }), client.getCode({ address: registry })]);
  const manifest = { source: "local-evm", chainId: 31337, rpcUrl: "http://127.0.0.1:8545", original, registry,
    originalCodeHash: keccak256(originalCode), registryCodeHash: keccak256(registryCode), genesisHash: genesis.hash,
    deploymentBlock: deployed.blockNumber.toString(), deploymentBlockHash: deploymentBlock.hash,
    accounts: accounts.slice(0, 3), samples, seededWorkId: "1" };
  await writeFile(path.join(dir, "deployment.json"), JSON.stringify(manifest, null, 2));
  await writeFile(path.join(dir, "gas.json"), JSON.stringify({ compiler: artifact.compiler, optimizer: 200, evmVersion: "shanghai", measurements: gas }, null, 2));
  console.log(JSON.stringify({ source: "LOCAL EVM ONLY", original, registry, seededWork: "1", versions: 3, gas }, null, 2));
  return manifest;
}
if (process.argv[1]?.endsWith("setup.mjs")) {
  try { await setup(); }
  catch(cause) { console.error(`Local setup refused: ${cause.shortMessage || cause.message}`); process.exitCode=1; }
}
